"""Install the p3 stages into an fhe-benchmarking/ml-inference checkout.

The suite's rules are explicit: the `harness/` directory must not change, and
a submission lives under `submissions/<dataset>/`. This script enforces the
first and performs the second, so the ranked evaluation runs through the
suite's own harness rather than a lookalike written here.

    python3 install_suite.py --check     # verify the checkout and report
    python3 install_suite.py --install   # write the stage shims
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

SUITE_DIR = Path(__file__).resolve().parent
CONFIG = json.loads((SUITE_DIR / "suite_config.json").read_text())
STAGES = ("client_key_generation", "client_preprocess_input",
          "client_encode_encrypt_input", "server_encrypted_compute",
          "client_decrypt_decode", "client_postprocess",
          "server_preprocess_model", "server_stop")


def suite_root() -> Path:
    root = Path(os.environ.get("MLINF_ROOT", Path.home() / "ml-inference"))
    if not (root / "harness" / "run_submission.py").is_file():
        raise SystemExit(
            f"{root} is not an ml-inference checkout.\n"
            f"  git clone {CONFIG['suite']['repository']} {root}\n"
            f"  git -C {root} checkout {CONFIG['suite']['commit']}\n"
            "or set MLINF_ROOT to an existing checkout.")
    return root


def harness_is_pristine(root: Path) -> tuple[bool, str]:
    """The suite forbids changing harness/; verify it against the pinned commit."""
    commit = CONFIG["suite"]["commit"]
    try:
        subprocess.run(["git", "-C", str(root), "cat-file", "-e", commit + "^{commit}"],
                       check=True, capture_output=True)
    except (subprocess.CalledProcessError, FileNotFoundError):
        return False, f"pinned commit {commit[:12]} not present in {root}"
    diff = subprocess.run(["git", "-C", str(root), "diff", "--stat", commit, "--", "harness"],
                          capture_output=True, text=True)
    untracked = subprocess.run(
        ["git", "-C", str(root), "ls-files", "--others", "--exclude-standard", "harness"],
        capture_output=True, text=True)
    if diff.stdout.strip() or untracked.stdout.strip():
        return False, (diff.stdout.strip() + "\n" + untracked.stdout.strip()).strip()
    return True, "harness/ is byte-identical to the pinned commit"


def install(root: Path) -> list[str]:
    target = root / CONFIG["suite"]["submission_subdir"]
    if target.exists():
        backup = target.with_name(target.name + ".orig")
        if not backup.exists():
            shutil.move(str(target), str(backup))
            print(f"  moved existing submission aside -> {backup}")
        else:
            shutil.rmtree(target)
    target.mkdir(parents=True, exist_ok=True)
    written = []
    for stage in STAGES:
        source = SUITE_DIR / "stages" / f"{stage}.py"
        shim = target / f"{stage}.py"
        # Client stages are CPU-side by definition: the client holds the key
        # pair and the slot layout and never touches the accelerator. Pinning
        # the platform here, before anything imports jax, also keeps a client
        # stage from colliding with the resident server for the one TPU.
        pin = ('os.environ.setdefault("JAX_PLATFORMS", "cpu")\n'
               if stage.startswith("client_") else "")
        shim.write_text(
            '#!/usr/bin/env python3\n'
            '"""Generated by agent_pset/p1_benchmark/src/suite/install_suite.py. Do not edit."""\n'
            "import os\n"
            "import runpy\n"
            "import sys\n\n"
            + pin
            + f'os.environ.setdefault("P3_SUITE_DIR", {str(SUITE_DIR)!r})\n'
            f'runpy.run_path({str(source)!r}, run_name="__main__")\n')
        shim.chmod(0o755)
        written.append(str(shim.relative_to(root)))
    # a submission that ships its own build script owns its whole build
    scripts = root / "scripts"
    scripts.mkdir(exist_ok=True)
    for name, body in (
        ("get_openfhe.sh", "#!/usr/bin/env bash\nset -euo pipefail\n"
                           "echo '[p3] CROSS submission: OpenFHE is not used.'\n"),
        ("build_task.sh", "#!/usr/bin/env bash\nset -euo pipefail\n"
                          "echo '[p3] CROSS is a JAX library; nothing to compile.'\n")):
        path = scripts / name
        if path.exists() and not path.read_text().startswith("#!/usr/bin/env bash\nset -euo pipefail\necho '[p3]"):
            backup = path.with_suffix(path.suffix + ".orig")
            if not backup.exists():
                shutil.copy2(path, backup)
        path.write_text(body)
        path.chmod(0o755)
        written.append(str(path.relative_to(root)))
    return written


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--install", action="store_true")
    args = ap.parse_args()

    root = suite_root()
    ok, detail = harness_is_pristine(root)
    print(f"suite checkout : {root}")
    print(f"pinned commit  : {CONFIG['suite']['commit']}")
    print(f"harness check  : {'OK' if ok else 'MODIFIED'} - {detail}")
    if not ok:
        raise SystemExit("harness/ differs from the pinned commit; restore it "
                         "before installing (the suite forbids harness changes).")
    if args.check:
        target = root / CONFIG["suite"]["submission_subdir"]
        installed = sorted(p.name for p in target.glob("*.py")) if target.exists() else []
        print(f"installed      : {installed or 'nothing yet (run --install)'}")
        # Say plainly what this installer changes outside the submission
        # directory. `harness/utils.py::build_submission` always runs both of
        # these, which for a pure-Python submission would download LibTorch and
        # build OpenFHE and then fail on a CMake project that no longer exists.
        # The suite's rule protects harness/, not scripts/, but a reader should
        # not have to diff the checkout to discover this.
        neutered = []
        for name in ("get_openfhe.sh", "build_task.sh"):
            path = root / "scripts" / name
            if path.exists() and "[p3]" in path.read_text():
                backup = path.with_suffix(path.suffix + ".orig")
                neutered.append(f"{name}"
                                + (f" (original at {backup.name})" if backup.exists()
                                   else " (NO BACKUP FOUND)"))
        print(f"scripts/       : {', '.join(neutered) if neutered else 'untouched'}")
        if neutered:
            print("                 replaced with no-ops; CROSS compiles nothing "
                  "and does not use OpenFHE")
        return
    written = install(root)
    print(f"installed {len(written)} files:")
    for path in written:
        print(f"  {path}")
    print("\nrun a case with:")
    print(f"  cd {root} && P3_DEVICES=1 P3_SUITE_DIR={SUITE_DIR} "
          "python3 harness/run_submission.py 0 --seed 3 --num_runs 3")


if __name__ == "__main__":
    main()
